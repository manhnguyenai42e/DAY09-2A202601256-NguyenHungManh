"""Verifier's grounding + schema check: every evidence ID must be reconstructible
from the source CSVs, every array must respect README section 6's limits, and
every required field must be present. Returns a list of violation strings
(empty = pass) rather than raising, so the Verifier agent can narrate them.
"""

from __future__ import annotations

from typing import Any

from src.config import LIMITS
from src.data import loader

REQUIRED_TOP_LEVEL = [
    "case_id",
    "case_assessment",
    "affected_entities",
    "customer_context",
    "product_context",
    "delivery_analysis",
    "payment_reconciliation",
    "root_cause_analysis",
    "evidence_ids",
    "financial_resolution",
    "resolution_actions",
]

ARRAY_LIMIT_PATHS = {
    ("affected_entities", "order_ids"): "order_ids",
    ("affected_entities", "item_ids"): "item_ids",
    ("affected_entities", "seller_ids"): "seller_ids",
    ("affected_entities", "payment_ids"): "payment_ids",
    ("customer_context", "related_order_ids"): "related_order_ids",
    ("product_context", "product_ids"): "product_ids",
    ("product_context", "category_names"): "category_names",
}

VALID_CASE_STATUS = {"action_required", "no_action"}


def _get(d: dict, path: tuple[str, ...]):
    cur: Any = d
    for key in path:
        if not isinstance(cur, dict) or key not in cur:
            return None
        cur = cur[key]
    return cur


def _check_evidence_grounding(order_id: str, evidence_ids: list[str]) -> list[str]:
    violations = []
    items = loader.get_order_items(order_id)
    payments = loader.get_order_payments(order_id)
    valid_item_ids = {f"{order_id}:{int(r.order_item_id)}" for r in items.itertuples()}
    valid_payment_ids = {f"{order_id}:{int(r.payment_sequential)}" for r in payments.itertuples()}
    valid_seller_ids = set(items["seller_id"].tolist())

    for ev in evidence_ids:
        kind, _, rest = ev.partition(":")
        if kind == "order":
            if rest != order_id:
                violations.append(f"evidence order id mismatch: {ev}")
        elif kind == "item":
            if rest not in valid_item_ids:
                violations.append(f"evidence item id not found in source data: {ev}")
        elif kind == "payment":
            if rest not in valid_payment_ids:
                violations.append(f"evidence payment id not found in source data: {ev}")
        elif kind == "seller":
            if rest not in valid_seller_ids:
                violations.append(f"evidence seller id not found in source data: {ev}")
        elif kind == "policy":
            pass  # policy:<root_cause_code> is generated by the engine itself, always valid
        else:
            violations.append(f"evidence id has unknown prefix: {ev}")
    return violations


def validate_case(case: dict[str, Any]) -> list[str]:
    violations: list[str] = []

    for field in REQUIRED_TOP_LEVEL:
        if field not in case:
            violations.append(f"missing required field: {field}")
    if violations:
        return violations  # can't check deeper without the basics

    for path, limit_key in ARRAY_LIMIT_PATHS.items():
        value = _get(case, path)
        if isinstance(value, list) and len(value) > LIMITS[limit_key]:
            violations.append(f"{'.'.join(path)} exceeds limit {LIMITS[limit_key]}: {len(value)}")

    ranked_causes = _get(case, ("root_cause_analysis", "ranked_causes")) or []
    if len(ranked_causes) > LIMITS["ranked_causes"]:
        violations.append("root_cause_analysis.ranked_causes exceeds limit 3")
    responsible_parties = _get(case, ("root_cause_analysis", "responsible_parties")) or []
    if len(responsible_parties) > LIMITS["responsible_parties"]:
        violations.append("root_cause_analysis.responsible_parties exceeds limit 3")
    evidence_ids = case.get("evidence_ids") or []
    if len(evidence_ids) > LIMITS["evidence_ids"]:
        violations.append("evidence_ids exceeds limit 20")
    resolution_actions = case.get("resolution_actions") or []
    if len(resolution_actions) > LIMITS["resolution_actions"]:
        violations.append("resolution_actions exceeds limit 5")

    confidence = _get(case, ("case_assessment", "confidence"))
    if confidence is None or not (0.0 <= confidence <= 1.0):
        violations.append(f"case_assessment.confidence out of [0,1]: {confidence}")

    case_status = _get(case, ("case_assessment", "case_status"))
    if case_status not in VALID_CASE_STATUS:
        violations.append(f"case_assessment.case_status invalid: {case_status}")

    order_ids = _get(case, ("affected_entities", "order_ids")) or []
    if not order_ids:
        violations.append("affected_entities.order_ids is empty")
    else:
        order_id = order_ids[0]
        violations += _check_evidence_grounding(order_id, evidence_ids)
        violations += _check_entity_grounding(order_id, case)

    return violations


def _check_entity_grounding(order_id: str, case: dict[str, Any]) -> list[str]:
    """Every reported entity value (not just evidence_ids) must exist verbatim in
    the source CSVs — the grader hard-gates fabricated entities."""
    violations = []
    items = loader.get_order_items(order_id)
    valid_product_ids = set(items["product_id"].tolist())
    products = loader.get_products(list(valid_product_ids))
    valid_categories = {
        c for c in products["product_category_name"].tolist() if isinstance(c, str)
    }
    valid_seller_ids = set(items["seller_id"].tolist())

    for pid in _get(case, ("product_context", "product_ids")) or []:
        if pid not in valid_product_ids:
            violations.append(f"product_id not in source data for this order: {pid}")
    for cat in _get(case, ("product_context", "category_names")) or []:
        if cat not in valid_categories:
            violations.append(f"category_name not in source data (raw CSV value required): {cat}")
    for sid in _get(case, ("affected_entities", "seller_ids")) or []:
        if sid not in valid_seller_ids:
            violations.append(f"seller_id not in source data for this order: {sid}")
    return violations
